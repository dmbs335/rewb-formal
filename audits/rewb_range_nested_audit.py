"""Audits the range-query and outer-repeat reductions for nested P2.
This checks the reductions, not the asymptotically optimal suffix-tree/ILP implementations.
Run: python rewb_range_nested_audit.py
"""
from itertools import product
from random import Random
rng=Random(420125)

def ident(k):return tuple(range(k))
def comp(f,g):return tuple(g[x] for x in f)
def tau(d,s):
    f=ident(len(d[0]))
    for a in s:f=comp(f,d[a])
    return f
def dfa(k):return tuple(tuple(rng.randrange(k) for _ in range(k)) for _ in range(2)),frozenset(i for i in range(k) if rng.randrange(2))
def accept(D,s):return tau(D[0],s)[0] in D[1]
def cluster_partition(occ,H):
    groups=[]
    for p in occ:
        if groups and 2*(p-groups[-1][-1])<=H:groups[-1].append(p)
        else:groups.append([p])
    return groups

def from_state(D,s,q=0): return tau(D[0],s)[q]
def acc(D,s,q=0):return from_state(D,s,q) in D[1]
def pw(g,k):
    f=ident(len(g))
    while k:
        if k&1:f=comp(f,g)
        g=comp(g,g);k//=2
    return f

def core(w,B,C,D):
    # B is the capture language, C the gap, D the suffix.
    n=len(w)
    return any(w[:a]==w[j:j+a] and accept(B,w[:a]) and accept(C,w[a:j]) and accept(D,w[j+a:]) for a in range(n//2+1) for j in range(a,n-a+1))

def one(w,A,B,C,E):
    return any(accept(A,w[:i]) and core(w[i:],B,C,E) for i in range(len(w)+1))

def inner(w,B,C,D,F): return one(w,B,C,D,F)

def equal_borders(x):return [i for i in range(1,len(x)//2+1) if x[:i]==x[-i:]]

def border_audit():
    count=0; families=0
    for n in range(1,12):
        for w in product(range(2),repeat=n):
            B,C=dfa(3),dfa(3)
            bs=equal_borders(w); d=1
            while d<=n//2:
                v=[a for a in bs if d<=a<2*d]
                d*=2
                if not v:continue
                families+=1
                if len(v)==1:continue
                q=v[1]-v[0]; k=len(v)-1
                assert v==[v[0]+j*q for j in range(k+1)]
                lo,hi=v[0],v[-1]
                gB=tau(B[0],w[lo:lo+q]); pB=tau(B[0],w[:lo]);
                gL=tau(C[0],w[hi-q:hi]); gR=tau(C[0],w[n-hi:n-hi+q]); m=tau(C[0],w[hi:n-hi])
                for j,a in enumerate(v):
                    assert comp(pB,pw(gB,j))==tau(B[0],w[:a])
                    assert comp(comp(pw(gL,k-j),m),pw(gR,k-j))==tau(C[0],w[a:n-a])
                    count+=1
    return families,count

def range_audit():
    queries=0
    for _ in range(160):
        n=rng.randrange(0,15); w=tuple(rng.randrange(2) for _ in range(n)); A,B,C,E=[dfa(rng.randrange(1,4)) for _ in range(4)]; b=rng.randrange(1,6)
        # The production tables are generated by the near-linear all-end/all-start routine.
        # These direct tables deliberately serve as semantic oracles only.
        for l in range(n+1):
            for r in range(l,n+1):
                L=((l+b-1)//b)*b; R=r//b*b
                fwd=False; rev=False
                if L<=r:
                    q=from_state(A,w[l:L]);
                    fwd=any(acc(A,w[L:i],q) and core(w[i:r],B,C,E) for i in range(L,r+1))
                if R>=l:
                    F=frozenset(q for q in range(len(E[0][0])) if from_state(E,w[R:r],q) in E[1]); E1=(E[0],F)
                    rev=one(w[l:R],A,B,C,E1)
                edge=False
                for i in range(l,min(r+1,L)):
                    if not accept(A,w[l:i]):continue
                    for f in range(max(i,R+1),r+1):
                        if not accept(E,w[f:r]):continue
                        x=w[i:f]; ls=[0]+equal_borders(x)
                        if any(accept(B,x[:a]) and accept(C,x[a:len(x)-a]) for a in ls):edge=True;break
                    if edge:break
                assert (fwd or rev or edge)==one(w[l:r],A,B,C,E),(w,l,r,b,A,B,C,E)
                queries+=1
    return queries

def maxpair(w,p,k):
    d=k-p; l=p;r=p
    while l>0 and w[l-1]==w[l-1+d]:l-=1
    while r+d<len(w) and w[r]==w[r+d]:r+=1
    return l,r,d

def period(w):return next(q for q in range(1,len(w)+1) if all(w[i]==w[i-q] for i in range(q,len(w))))

def cover_audit():
    count=non=over=largegap=smallgap=0
    for n in range(2,11):
        for w in product(range(2),repeat=n):
            for p in range(n):
                for k in range(p+1,n):
                    l,r,d=maxpair(w,p,k); M=r-l
                    for e in range(p+1,min(r,k)+1):
                        if e+d>n:continue
                        count+=1
                        assert w[p:e]==w[k:e+d]
                        if M<=d:
                            non+=1
                            for L in range(1,e-p):
                                x=((p+L-1)//L)*L
                                assert p<=x<e and l<=x<r
                        else:
                            over+=1; R=r+d;q=period(w[l:R]);N=R-l
                            assert d%q==0 and N>=2*d
                            assert l==0 or w[l-1]!=w[l-1+q]
                            assert R==n or w[R]!=w[R-q]
                            for D in range(1,5):
                                if k-e>=D:
                                    largegap+=1;c=((e+D-1)//D)*D
                                    assert e<=c<=k
                                    L=max(l,c-d); U=min(r,c)
                                    assert L<=p<e<=U<=L+d
                                else:
                                    smallgap+=1;c=min(p+d,R-d)
                                    assert e<=c
                                    if N<3*q:
                                        assert d==q and p<=R-2*q+D
    return count,non,over,largegap,smallgap

def factor_audit():
    tests=positive=0; pt=0;pp=0
    for _ in range(4200):
        # Plant repeated fragments, optionally overlapping via periodic base.
        n=rng.randrange(2,25); q=rng.randrange(1,7); base=tuple(rng.randrange(2) for _ in range(q))
        if rng.randrange(2):
            w=tuple(rng.randrange(2) for _ in range(n))
        else:
            w=(base*((n+q-1)//q))[:n]
        A,B,C,D,F,G,H=[dfa(rng.randrange(1,4)) for _ in range(7)]
        p=rng.randrange(n-1);k=rng.randrange(p+1,n);l,r,d=maxpair(w,p,k)
        if r<=p:continue
        # For nonoverlap use maximal interval, or a truncated interval at a cut.
        if r-l>d:
            cut=rng.randrange(l,r+d+1);l1=max(l,cut-d);r1=min(r,cut)
        else:l1,r1=l,r
        if l1<r1:
            assert r1<=l1+d
            X=w[l1:r1]; middle=w[r1:l1+d]; out=w[r1+d:];
            exact=any(accept(A,w[:i]) and inner(w[i:e],B,C,D,F) and accept(G,w[e:i+d]) and accept(H,w[e+d:]) for i in range(l1,r1+1) for e in range(i,r1+1))
            translated=False
            for g in range(len(G[0][0])):
                for i in range(len(X)+1):
                    pre=X[:i]
                    if not (acc(A,pre,from_state(A,w[:l1])) and acc(G,pre,from_state(G,middle,g))):continue
                    for e in range(i,len(X)+1):
                        tail=X[e:]
                        if from_state(G,tail)!=g or not acc(H,out,from_state(H,tail)):continue
                        if inner(X[i:e],B,C,D,F):translated=True;break
                    if translated:break
                if translated:break
            assert exact==translated
            tests+=1;positive+=exact
        if r-l>d:
            c=min(p+d,r)
            exact=accept(A,w[:p]) and any(inner(w[p:e],B,C,D,F) and accept(G,w[e:p+d]) and accept(H,w[e+d:]) for e in range(p,c+1))
            tr=accept(A,w[:p]) and any(inner(w[p:e],B,C,D,F) and acc(G,w[c:p+d],from_state(G,w[e:c])) and acc(H,w[c+d:],from_state(H,w[e:c])) for e in range(p,c+1))
            assert exact==tr;pt+=1;pp+=exact
    return tests,positive,pt,pp

def residue_audit():
    tests=0
    for _ in range(10000):
        q=rng.randrange(1,10);V=tuple(rng.randrange(2) for _ in range(q))
        if any(q%d==0 and V==V[:d]*(q//d) for d in range(1,q)):continue
        n=rng.randrange(2*q,8*q+1);w=(V*((n+q-1)//q))[:n];D=dfa(rng.randrange(1,5))
        i,j=sorted(rng.sample(range(n+1),2));a=rng.randrange(0,n-j+1)
        ri,rj=i%q,j%q
        eq=w[i:i+a]==w[j:j+a]
        predicted=(ri==rj or (a<q and (V*2)[ri:ri+a]==(V*2)[rj:rj+a]))
        assert eq==predicted
        x,y=sorted([rng.randrange(n+1),rng.randrange(n+1)]);k1,r1=divmod(x,q);k2,r2=divmod(y,q)
        if k1==k2:g=tau(D[0],V[r1:r2])
        else:g=comp(comp(tau(D[0],V[r1:]),pw(tau(D[0],V),k2-k1-1)),tau(D[0],V[:r2]))
        assert g==tau(D[0],w[x:y]);tests+=1
    return tests

def lazy_audit():
    checks=0
    for _ in range(1500):
        n=rng.randrange(3,40);q=rng.randrange(1,9);V=tuple(rng.randrange(2) for _ in range(q));w=(V*((n+q-1)//q))[:n]
        if rng.randrange(2):w=tuple(rng.randrange(2) for _ in range(n))
        C=dfa(4);s=rng.randrange(n);H=rng.randrange(1,n-s+1);X=w[s:s+H];occ=[i for i in range(n-H+1) if w[i:i+H]==X];groups=cluster_partition(occ,H)
        for L in range(1,H):
            if [i for i in range(n-L+1) if w[i:i+L]==X[:L]]!=occ:continue
            if cluster_partition(occ,L)!=groups:continue
            if any((y-x<H)!=(y-x<L) for x,y in zip(occ,occ[1:])):continue
            tail=tau(C[0],X[L:H]);
            for idx,g in enumerate(groups):
                nxt=groups[idx+1][0] if idx+1<len(groups) else n
                if idx and groups[idx-1][-1]+H>g[0]:
                    prev=groups[idx-1][-1];assert comp(tail,tau(C[0],w[prev+H:nxt]))==tau(C[0],w[prev+L:nxt]);checks+=1
                    if len(g)>1:
                        assert comp(tail,tau(C[0],w[prev+H:g[1]]))==tau(C[0],w[prev+L:g[1]]);checks+=1
                v=len(g)-1-(g[-1]+H>nxt)
                if v>=0:
                    assert comp(tail,tau(C[0],w[g[v]+H:nxt]))==tau(C[0],w[g[v]+L:nxt]);checks+=1
    return checks

if __name__=='__main__':
    print('border families / power checks:',border_audit(),flush=True)
    print('range queries:',range_audit(),flush=True)
    print('coverage: witnesses / nonoverlap / overlap / largegap / smallgap:',cover_audit(),flush=True)
    print('factorization: nonoverlap tests / positive / fixed-start tests / positive:',factor_audit(),flush=True)
    print('period phase and transition checks:',residue_audit(),flush=True)
    print('lazy boundary transformations:',lazy_audit(),flush=True)
